// ─── telemetry parity (end-to-end via subprocess) ────────────────────────
//
// Verifies the hook actually writes to ~/.claude-telemetry/. Each test
// redirects via CLAUDE_TELEMETRY_ROOT so it doesn't pollute the
// operator's real log dir. Catches regressions like the long-standing
// `tool` ReferenceError that silently swallowed every docgen telemetry
// fire from #12 until this PR.

function runHookWithTelemetry(payload, { sessionId, telemetryRoot }) {
  const full = sessionId ? { ...payload, session_id: sessionId } : payload;
  return spawnSync('node', [HOOK], {
    input: JSON.stringify(full),
    encoding: 'utf8',
    env: {
      ...process.env,
      DOCGEN_HOOK_TRACE: '0',
      CLAUDE_TELEMETRY_ROOT: telemetryRoot,
    },
  });
}

function readTelemetry(telemetryRoot, sessionId) {
  const path = join(telemetryRoot, 'sessions', `${sessionId}.jsonl`);
  if (!existsSync(path)) return [];
  return readFileSync(path, 'utf8')
    .trim()
    .split('\n')
    .filter(Boolean)
    .map((l) => JSON.parse(l));
}

test('telemetry: writes one `injected` row when README(s) get emitted', () => {
  const root = freshGitRepo();
  const telemetryRoot = mkdtempSync(join(tmpdir(), 'docgen-telem-'));
  const sessionId = 'telem-inject-test';
  try {
    file(root, 'AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nROOT MAP');
    file(root, 'src/AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nSRC MAP');
    file(root, 'src/app.js', 'console.log("x")');
    clearDedup(sessionId);

    const r = runHookWithTelemetry(
      { tool_name: 'Read', tool_input: { file_path: join(root, 'src/app.js') } },
      { sessionId, telemetryRoot },
    );
    assert.equal(r.status, 0);

    const rows = readTelemetry(telemetryRoot, sessionId);
    assert.equal(rows.length, 1, 'should land exactly one telemetry row');
    assert.equal(rows[0].hook, 'docgen-inject-readme-context');
    assert.equal(rows[0].event, 'injected');
    assert.equal(rows[0].tool, 'Read');
    assert.ok(rows[0].bytes_emitted > 0, 'bytes_emitted must reflect real payload size');
    assert.ok(
      Array.isArray(rows[0].files_injected) && rows[0].files_injected.length >= 1,
      'files_injected must list the READMEs that were emitted',
    );

    clearDedup(sessionId);
  } finally {
    rmSync(root, { recursive: true, force: true });
    rmSync(telemetryRoot, { recursive: true, force: true });
  }
});

test('telemetry: writes a `deduped` row on the second call in the same session', () => {
  const root = freshGitRepo();
  const telemetryRoot = mkdtempSync(join(tmpdir(), 'docgen-telem-'));
  const sessionId = 'telem-dedup-test';
  try {
    file(root, 'AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nROOT');
    file(root, 'src/AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nSRC');
    file(root, 'src/a.js', 'a');
    clearDedup(sessionId);

    // First fire — injects.
    runHookWithTelemetry(
      { tool_name: 'Read', tool_input: { file_path: join(root, 'src/a.js') } },
      { sessionId, telemetryRoot },
    );
    // Second fire on a sibling file — every README in the chain is
    // already in the dedup set, so collected becomes empty → deduped.
    file(root, 'src/b.js', 'b');
    runHookWithTelemetry(
      { tool_name: 'Read', tool_input: { file_path: join(root, 'src/b.js') } },
      { sessionId, telemetryRoot },
    );

    const rows = readTelemetry(telemetryRoot, sessionId);
    assert.equal(rows.length, 2, 'first fire = injected, second = deduped');
    assert.equal(rows[0].event, 'injected');
    assert.equal(rows[1].event, 'deduped');
    assert.equal(rows[1].bytes_emitted, 0);
    assert.equal(rows[1].tool, 'Read');

    clearDedup(sessionId);
  } finally {
    rmSync(root, { recursive: true, force: true });
    rmSync(telemetryRoot, { recursive: true, force: true });
  }
});

test('telemetry: writes NOTHING for out-of-repo paths (no fake-deduped noise)', () => {
  const telemetryRoot = mkdtempSync(join(tmpdir(), 'docgen-telem-'));
  const sessionId = 'telem-out-of-repo-test';
  try {
    // Point at a file outside any git repo: /tmp itself isn't a git
    // repo, so repoRoot() returns null and the hook bails before any
    // injection. The previous `deduped` event would have been emitted
    // — now it must NOT be.
    const outsideFile = join(telemetryRoot, 'not-in-repo.txt');
    writeFileSync(outsideFile, 'hi');

    runHookWithTelemetry(
      { tool_name: 'Read', tool_input: { file_path: outsideFile } },
      { sessionId, telemetryRoot },
    );

    const rows = readTelemetry(telemetryRoot, sessionId);
    assert.equal(
      rows.length,
      0,
      'out-of-repo fires must exit silently — no telemetry row',
    );
  } finally {
    rmSync(telemetryRoot, { recursive: true, force: true });
  }
});

