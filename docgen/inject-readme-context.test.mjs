/**
 * Tests for the README-injection hook.
 *
 * Run with:  node --test tools/docgen/inject-readme-context.test.mjs
 *
 * Spawns the hook as a real subprocess (matching how Claude Code runs
 * it) with constructed stdin payloads and asserts on stdout + the
 * dedup state.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import {
  mkdtempSync,
  mkdirSync,
  writeFileSync,
  rmSync,
  existsSync,
  readFileSync,
} from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HOOK = join(
  dirname(fileURLToPath(import.meta.url)),
  'inject-readme-context.mjs',
);

/** Build a tmp git repo so the hook's `git rev-parse` succeeds. */
function freshGitRepo() {
  const root = mkdtempSync(join(tmpdir(), 'docgen-hook-'));
  execFileSync('git', ['init', '-q'], { cwd: root });
  // Suppress any user-level identity prompts.
  execFileSync('git', ['config', 'user.email', 'test@test'], { cwd: root });
  execFileSync('git', ['config', 'user.name', 'test'], { cwd: root });
  return root;
}

function file(root, rel, content) {
  const full = join(root, rel);
  mkdirSync(join(full, '..'), { recursive: true });
  writeFileSync(full, content);
  return full;
}

/** Invoke the hook with a payload; return { stdout, stderr, status }. */
function runHook(payload, { sessionId } = {}) {
  const full = sessionId
    ? { ...payload, session_id: sessionId }
    : payload;
  const r = spawnSync('node', [HOOK], {
    input: JSON.stringify(full),
    encoding: 'utf8',
    env: { ...process.env, DOCGEN_HOOK_TRACE: '0' },
  });
  return { stdout: r.stdout, stderr: r.stderr, status: r.status };
}

function clearDedup(sessionId) {
  const p = `/tmp/docgen-injected-${sessionId.replace(/[^A-Za-z0-9_-]/g, '_')}.json`;
  if (existsSync(p)) rmSync(p);
}

test('hook injects nearest AUTO_DOCS.md + ancestor AUTO_DOCS.md for a Read', () => {
  const root = freshGitRepo();
  try {
    file(root, 'AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nROOT README');
    file(root, 'pkg/AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nPKG README');
    file(root, 'pkg/sub/AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nSUB README');
    file(root, 'pkg/sub/file.ts', '// code');

    const sessionId = 'sess-' + Date.now();
    clearDedup(sessionId);
    const { stdout, status } = runHook(
      {
        tool_name: 'Read',
        tool_input: { file_path: join(root, 'pkg/sub/file.ts') },
      },
      { sessionId },
    );
    assert.equal(status, 0, 'hook must exit 0');
    assert.match(stdout, /SUB README/);
    assert.match(stdout, /PKG README/);
    assert.match(stdout, /ROOT README/);
    // Root-most first (broadest context at the top).
    const rootIdx = stdout.indexOf('ROOT README');
    const pkgIdx = stdout.indexOf('PKG README');
    const subIdx = stdout.indexOf('SUB README');
    assert.ok(rootIdx < pkgIdx, 'root must precede pkg');
    assert.ok(pkgIdx < subIdx, 'pkg must precede sub');
    clearDedup(sessionId);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('hook DEDUPS within a session — second call emits nothing', () => {
  const root = freshGitRepo();
  try {
    file(root, 'AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nROOT');
    file(root, 'a.ts', '// code');

    const sessionId = 'sess-dedup-' + Date.now();
    clearDedup(sessionId);

    const r1 = runHook(
      { tool_name: 'Read', tool_input: { file_path: join(root, 'a.ts') } },
      { sessionId },
    );
    assert.ok(r1.stdout.includes('ROOT'));

    const r2 = runHook(
      { tool_name: 'Read', tool_input: { file_path: join(root, 'a.ts') } },
      { sessionId },
    );
    assert.equal(r2.stdout, '', 'second call must dedup and emit nothing');
    clearDedup(sessionId);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

