test('hook injects AUTO_DOCS.md + CLAUDE.md but IGNORES a hand-written README.md', () => {
  const root = freshGitRepo();
  try {
    // A hand-written README.md sits in pkg/ — docgen owns AUTO_DOCS.md now,
    // so README.md must be invisible to the injection hook.
    file(root, 'pkg/README.md', '# My project\n\nHand-tuned, humans own this.');
    // The generated map lives at AUTO_DOCS.md.
    file(root, 'pkg/AUTO_DOCS.md', '<!-- auto-generated by docgen -->\n## Purpose\nGenerated map.');
    // A hand-written CLAUDE.md sidecar is still injected.
    file(root, 'pkg/CLAUDE.md', 'Rule: never do the bad thing.');
    file(root, 'pkg/code.ts', '// code');

    const sessionId = 'sess-mixed-' + Date.now();
    clearDedup(sessionId);
    const r = runHook(
      { tool_name: 'Read', tool_input: { file_path: join(root, 'pkg/code.ts') } },
      { sessionId },
    );
    assert.ok(r.stdout.includes('Generated map.'), 'generated AUTO_DOCS.md must be included');
    assert.ok(r.stdout.includes('never do the bad thing'), 'CLAUDE.md sidecar must be included');
    assert.ok(!r.stdout.includes('My project'),
      'hand-written README.md must NOT be injected — humans own it');
    clearDedup(sessionId);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('hook records the agents EXPLICIT AUTO_DOCS.md reads — skips them on later injection', () => {
  const root = freshGitRepo();
  try {
    file(root, 'AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nROOT');
    file(root, 'pkg/AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nPKG');
    file(root, 'pkg/sub/AUTO_DOCS.md', '<!-- auto-generated by docgen -->\nSUB');
    file(root, 'pkg/sub/file.ts', '// code');

    const sessionId = 'sess-explicit-' + Date.now();
    clearDedup(sessionId);

    // 1) Agent EXPLICITLY Reads pkg/AUTO_DOCS.md — hook NOOPs (no
    //    self-injection) but should record it as "already in context".
    const r1 = runHook(
      { tool_name: 'Read', tool_input: { file_path: join(root, 'pkg/AUTO_DOCS.md') } },
      { sessionId },
    );
    assert.equal(r1.stdout, '', 'reading an AUTO_DOCS.md itself must NOT emit injection');

    // 2) Agent Reads a sibling source file. Ancestor walk would include
    //    root, pkg, pkg/sub. But pkg/AUTO_DOCS.md was already Read, so it
    //    must be skipped while the others still appear.
    const r2 = runHook(
      { tool_name: 'Read', tool_input: { file_path: join(root, 'pkg/sub/file.ts') } },
      { sessionId },
    );
    assert.ok(r2.stdout.includes('ROOT'), 'root AUTO_DOCS.md must still appear');
    assert.ok(r2.stdout.includes('SUB'), 'sub AUTO_DOCS.md must still appear');
    assert.ok(!r2.stdout.includes('PKG'),
      `pkg AUTO_DOCS.md must NOT reappear — agent already read it. Got: ${r2.stdout.slice(0, 300)}`);

    clearDedup(sessionId);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

