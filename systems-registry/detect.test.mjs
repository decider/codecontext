import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { detect, _internal } from './detect.mjs';

function fixture(spec) {
  const root = mkdtempSync(join(tmpdir(), 'sr-detect-'));
  for (const [path, body] of Object.entries(spec)) {
    const full = join(root, path);
    mkdirSync(join(full, '..'), { recursive: true });
    writeFileSync(full, body);
  }
  return root;
}

describe('signalCoordinator', () => {
  it('fires when a top-level file imports >=2 siblings', () => {
    const root = fixture({
      'tools/loop/run.mjs': "import { capture } from './capture.mjs';\nimport { score } from './score.mjs';\n",
      'tools/loop/capture.mjs': 'export const capture = () => {};\n',
      'tools/loop/score.mjs': 'export const score = () => {};\n',
    });
    try {
      const r = _internal.scoreDir(join(root, 'tools/loop'), root);
      assert.equal(r.signals.coordinator, true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('handles Python-style imports without `from`', () => {
    const root = fixture({
      'pkg/main.py': 'import sibling_a\nimport sibling_b\nx = 1\n',
      'pkg/sibling_a.py': 'a = 1\n',
      'pkg/sibling_b.py': 'b = 1\n',
    });
    try {
      const r = _internal.scoreDir(join(root, 'pkg'), root);
      assert.equal(r.signals.coordinator, true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('does not fire when no siblings imported', () => {
    const root = fixture({
      'pkg/a.mjs': 'export const a = 1;\n',
      'pkg/b.mjs': 'export const b = 2;\n',
      'pkg/c.mjs': 'export const c = 3;\n',
    });
    try {
      const r = _internal.scoreDir(join(root, 'pkg'), root);
      assert.equal(r.signals.coordinator, false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});

