describe('signalSpecOrReadme', () => {
  it('counts hand-written README', () => {
    const root = fixture({ 'pkg/README.md': '# hand-written\nthis is a real readme' });
    try {
      const r = _internal.scoreDir(join(root, 'pkg'), root);
      assert.equal(r.signals['spec-or-readme'], true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('rejects docgen-generated READMEs (marker at top)', () => {
    const root = fixture({ 'pkg/README.md': '<!-- auto-generated by docgen -->\nbody' });
    try {
      const r = _internal.scoreDir(join(root, 'pkg'), root);
      assert.equal(r.signals['spec-or-readme'], false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('does NOT reject when the marker is only mentioned in prose', () => {
    const root = fixture({ 'pkg/README.md': '# my tool\n\nthis writes READMEs with "auto-generated by docgen" marker.\n' });
    try {
      const r = _internal.scoreDir(join(root, 'pkg'), root);
      assert.equal(r.signals['spec-or-readme'], true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('counts ALL_CAPS docs', () => {
    const root = fixture({ 'pkg/PRICE_MODELING.md': '# modelling' });
    try {
      const r = _internal.scoreDir(join(root, 'pkg'), root);
      assert.equal(r.signals['spec-or-readme'], true);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});

describe('detect (end-to-end)', () => {
  it('finds a system that hits >=4 signals', () => {
    const root = fixture({
      'tools/example/run.mjs':
        `import { spawn } from 'node:child_process';\n` +
        `import { capture } from './capture.mjs';\n` +
        `import { score } from './score.mjs';\n` +
        `while (true) {\n  spawn('claude', ['-p']);\n}\n` +
        `import { writeFileSync } from 'fs';\nwriteFileSync('state.json', '{}');\n`,
      'tools/example/capture.mjs': 'export const capture = () => {};\n',
      'tools/example/score.mjs': 'export const score = () => {};\n',
      'tools/example/run.test.mjs': "import { test } from 'node:test';\ntest('a', () => {});",
      'tools/example/capture.test.mjs': "import { test } from 'node:test';\ntest('b', () => {});",
      'tools/example/score.test.mjs': "import { test } from 'node:test';\ntest('c', () => {});",
      'tools/example/README.md': '# example tool',
    });
    try {
      const found = detect(root);
      assert.ok(found.length >= 1);
      const ex = found.find(s => s.dir === 'tools/example');
      assert.ok(ex, 'tools/example should be detected');
      assert.ok(ex.score >= 4);
      assert.ok(ex.signals.includes('coordinator'));
      assert.ok(ex.signals.includes('persistent-state'));
      assert.ok(ex.signals.includes('loop'));
      assert.ok(ex.signals.includes('subprocess'));
      assert.ok(ex.signals.includes('tests'));
      assert.ok(ex.signals.includes('spec-or-readme'));
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('rejects a small utility library (score < 4)', () => {
    const root = fixture({
      'packages/util/index.mjs': "export const add = (a,b) => a+b;\nexport const sub = (a,b) => a-b;\n",
      'packages/util/README.md': '# util',
    });
    try {
      const found = detect(root);
      const util = found.find(s => s.dir === 'packages/util');
      assert.equal(util, undefined, 'small util lib should NOT be detected');
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});
